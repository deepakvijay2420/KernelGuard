#!/bin/bash

set -u

PROJECT="/home/deepak/kernelguard"
AGENT_DIR="$PROJECT/agents/langchain_agent"
LAB_DIR="/tmp/kernelguard-agent-lab"
IDENTITY_DIR="$PROJECT/logs/agent_identity"

mkdir -p "$IDENTITY_DIR"

TIMESTAMP=$(date +"%Y%m%d_%H%M%S")

IDENTITY_LOG="$IDENTITY_DIR/agent_identity_$TIMESTAMP.log"
EVENT_LOG="$IDENTITY_DIR/kernelguard_events_$TIMESTAMP.log"
PROCESS_LOG="$IDENTITY_DIR/process_tree_$TIMESTAMP.log"

echo
echo "=============================================================="
echo " KernelGuard Agent Identity & Correlation Test"
echo "=============================================================="
echo

# ==============================================================
# 1. Activate environment
# ==============================================================

if [ ! -d "$AGENT_DIR/.venv" ]; then
    echo "[ERROR] Python virtual environment not found."
    exit 1
fi

source "$AGENT_DIR/.venv/bin/activate"

echo "[OK] Python environment activated"

# ==============================================================
# 2. Check Gemini API key
# ==============================================================

if [ -z "${GOOGLE_API_KEY:-}" ]; then

    echo
    echo "[+] Gemini API key required."
    echo "[+] Enter your NEW Gemini API key."
    echo

    read -r -s -p "Gemini API key: " GOOGLE_API_KEY
    echo

    export GOOGLE_API_KEY
fi

if [ -z "${GOOGLE_API_KEY:-}" ]; then
    echo "[ERROR] Gemini API key not available."
    exit 1
fi

echo "[OK] Gemini API key available"

# ==============================================================
# 3. Check KernelGuard
# ==============================================================

echo
echo "=============================================================="
echo " Checking KernelGuard"
echo "=============================================================="

if ! systemctl is-active --quiet kernelguard-ebpf.service; then
    echo "[+] Starting KernelGuard eBPF service..."
    sudo systemctl start kernelguard-ebpf.service
    sleep 2
fi

if ! systemctl is-active --quiet kernelguard-reader.service; then
    echo "[+] Starting KernelGuard reader service..."
    sudo systemctl start kernelguard-reader.service
    sleep 2
fi

if systemctl is-active --quiet kernelguard-ebpf.service; then
    echo "[OK] KernelGuard eBPF service running"
else
    echo "[ERROR] KernelGuard eBPF service not running"
    exit 1
fi

if systemctl is-active --quiet kernelguard-reader.service; then
    echo "[OK] KernelGuard reader running"
else
    echo "[ERROR] KernelGuard reader not running"
    exit 1
fi

# ==============================================================
# 4. Prepare controlled test directory
# ==============================================================

echo
echo "=============================================================="
echo " Preparing Agent Test Environment"
echo "=============================================================="

sudo mkdir -p "$LAB_DIR"
sudo chown "$USER":"$USER" "$LAB_DIR"

cat > "$LAB_DIR/research.txt" <<'EOF'
KernelGuard Agent Identity Experiment

This controlled file is used to test whether Linux
process execution generated by the LangChain Agent
can be correlated with the Agent process.

Agent ID:
research_agent_01
EOF

echo "[OK] Controlled test directory ready"

# ==============================================================
# 5. Create agent program
# ==============================================================

cat > "$AGENT_DIR/kernelguard_identity_agent.py" <<'PYTHON'
import os
import subprocess
import time

from langchain.agents import create_agent
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain.tools import tool


# ==============================================================
# Agent Identity
# ==============================================================

AGENT_ID = "research_agent_01"
TEST_DIR = "/tmp/kernelguard-agent-lab"

PID_FILE = "/tmp/kernelguard_agent_pid"

# Save agent PID
with open(PID_FILE, "w") as f:
    f.write(str(os.getpid()))


print()
print("==================================================")
print(" KernelGuard Research Agent")
print("==================================================")
print("Agent ID :", AGENT_ID)
print("Agent PID:", os.getpid())
print("Parent PID:", os.getppid())
print("Test Dir :", TEST_DIR)
print("PID file :", PID_FILE)
print()


# ==============================================================
# Tool 1
# ==============================================================

@tool
def list_files() -> str:
    """
    List files inside the controlled KernelGuard
    test directory.
    """

    print("[TOOL] list_files()")
    print("[TOOL PID]", os.getpid())

    result = subprocess.run(
        ["ls", "-la", TEST_DIR],
        capture_output=True,
        text=True,
        timeout=5
    )

    return result.stdout


# ==============================================================
# Tool 2
# ==============================================================

@tool
def read_research_file() -> str:
    """
    Read the controlled research file.
    """

    print("[TOOL] read_research_file()")
    print("[TOOL PID]", os.getpid())

    file_path = os.path.join(
        TEST_DIR,
        "research.txt"
    )

    result = subprocess.run(
        ["cat", file_path],
        capture_output=True,
        text=True,
        timeout=5
    )

    return result.stdout


# ==============================================================
# Gemini
# ==============================================================

model = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash"
)


# ==============================================================
# Security Policy
# ==============================================================

SYSTEM_PROMPT = """
You are research_agent_01 running inside the
KernelGuard cybersecurity experiment.

You are operating in a controlled Linux environment.

Allowed operations:

1. List files in:
   /tmp/kernelguard-agent-lab

2. Read:
   /tmp/kernelguard-agent-lab/research.txt

You MUST use the provided tools for these operations.

Security restrictions:

- Never use sudo.
- Never execute arbitrary shell commands.
- Never access /etc.
- Never access /root.
- Never access the user's home directory.
- Never access files outside the controlled test directory.
- Never perform network operations.
- Never perform privileged operations.

This experiment is specifically measuring Linux
process execution generated by an Agentic AI system.
"""


# ==============================================================
# Create Agent
# ==============================================================

agent = create_agent(
    model=model,
    tools=[
        list_files,
        read_research_file
    ],
    system_prompt=SYSTEM_PROMPT
)


# ==============================================================
# Execute Agent
# ==============================================================

print("Sending task to LangChain Agent...")
print()

response = agent.invoke(
    {
        "messages": [
            {
                "role": "user",
                "content": (
                    "Inspect the KernelGuard test directory. "
                    "List the files and then read research.txt. "
                    "Give me a short summary."
                )
            }
        ]
    }
)


# ==============================================================
# Final response
# ==============================================================

print()
print("==================================================")
print(" Agent Response")
print("==================================================")
print()

messages = response.get("messages", [])

if messages:
    final_message = messages[-1]

    if hasattr(final_message, "content"):
        print(final_message.content)
    else:
        print(final_message)

print()
print("Agent execution completed.")

# Keep process alive briefly so parent/process information
# can be inspected by the wrapper script.
time.sleep(2)

PYTHON

echo "[OK] Agent program created"

# ==============================================================
# 6. Clear old PID
# ==============================================================

rm -f /tmp/kernelguard_agent_pid

# ==============================================================
# 7. Record current KernelGuard log position
# ==============================================================

sudo journalctl \
    -u kernelguard-reader.service \
    --since "1 second ago" \
    --no-pager > "$EVENT_LOG" 2>/dev/null || true

# ==============================================================
# 8. Start agent in background
# ==============================================================

echo
echo "=============================================================="
echo " Starting Agent"
echo "=============================================================="
echo

python "$AGENT_DIR/kernelguard_identity_agent.py" \
    > "$IDENTITY_LOG" 2>&1 &

AGENT_WRAPPER_PID=$!

echo "[OK] Agent launcher PID: $AGENT_WRAPPER_PID"

# ==============================================================
# 9. Wait for agent PID
# ==============================================================

AGENT_PID=""

for i in $(seq 1 20); do

    if [ -f /tmp/kernelguard_agent_pid ]; then

        AGENT_PID=$(cat /tmp/kernelguard_agent_pid)

        if [ -n "$AGENT_PID" ]; then
            break
        fi

    fi

    sleep 0.5
done

if [ -z "$AGENT_PID" ]; then

    echo
    echo "[ERROR] Could not obtain Agent PID."

    cat "$IDENTITY_LOG"

    kill "$AGENT_WRAPPER_PID" 2>/dev/null || true

    exit 1
fi

echo
echo "[OK] Agent PID: $AGENT_PID"

# ==============================================================
# 10. Collect Agent process information
# ==============================================================

echo
echo "=============================================================="
echo " Agent Process Identity"
echo "=============================================================="

echo "Agent ID: research_agent_01" | tee "$PROCESS_LOG"
echo "Agent PID: $AGENT_PID" | tee -a "$PROCESS_LOG"

echo
echo "Process information:"
ps -p "$AGENT_PID" \
    -o pid,ppid,uid,user,comm,args \
    | tee -a "$PROCESS_LOG"

echo
echo "Parent process:"
PPID=$(ps -p "$AGENT_PID" -o ppid= | tr -d ' ')

if [ -n "$PPID" ]; then

    ps -p "$PPID" \
        -o pid,ppid,uid,user,comm,args \
        | tee -a "$PROCESS_LOG"

fi

echo
echo "Process tree:"
pstree -aps "$AGENT_PID" \
    | tee -a "$PROCESS_LOG" || true

# ==============================================================
# 11. Wait for agent completion
# ==============================================================

echo
echo "=============================================================="
echo " Waiting for Agent"
echo "=============================================================="

wait "$AGENT_WRAPPER_PID" || true

# ==============================================================
# 12. Collect KernelGuard events
# ==============================================================

echo
echo "=============================================================="
echo " KernelGuard Events Generated During Agent Execution"
echo "=============================================================="

sudo journalctl \
    -u kernelguard-reader.service \
    --since "2 minutes ago" \
    --no-pager \
    | tee "$EVENT_LOG"

# ==============================================================
# 13. Search for relevant execution events
# ==============================================================

echo
echo "=============================================================="
echo " Agent-Related Executions"
echo "=============================================================="

grep -E \
    "ls|cat|EXEC|research|kernelguard-agent-lab" \
    "$EVENT_LOG" \
    || echo "[INFO] No matching event text found."

# ==============================================================
# 14. Display tool information
# ==============================================================

echo
echo "=============================================================="
echo " Agent Tool Execution Log"
echo "=============================================================="

cat "$IDENTITY_LOG"

# ==============================================================
# 15. Save correlation summary
# ==============================================================

SUMMARY_FILE="$IDENTITY_DIR/correlation_$TIMESTAMP.txt"

cat > "$SUMMARY_FILE" <<EOF
KernelGuard Agent Correlation Experiment
==========================================

Agent ID:
research_agent_01

Agent PID:
$AGENT_PID

Agent launcher PID:
$AGENT_WRAPPER_PID

Test directory:
$LAB_DIR

Agent program:
$AGENT_DIR/kernelguard_identity_agent.py

Observed tools:
list_files()
read_research_file()

Expected Linux executions:
 /usr/bin/ls
 /usr/bin/cat

KernelGuard service:
kernelguard-reader.service

Identity evidence:
$PROCESS_LOG

KernelGuard evidence:
$EVENT_LOG

Agent execution output:
$IDENTITY_LOG
EOF

# ==============================================================
# 16. Final output
# ==============================================================

echo
echo "=============================================================="
echo " Agent Identity Experiment Completed"
echo "=============================================================="

echo
echo "Agent ID : research_agent_01"
echo "Agent PID: $AGENT_PID"

echo
echo "Logs saved under:"
echo "$IDENTITY_DIR"

echo
echo "Summary:"
echo "$SUMMARY_FILE"

echo
echo "=============================================================="
echo " CURRENT ARCHITECTURE"
echo "=============================================================="

echo
echo "Gemini"
echo "  ↓"
echo "LangChain Agent"
echo "  ↓"
echo "Agent PID"
echo "  ↓"
echo "Agent Tool"
echo "  ↓"
echo "Linux Process"
echo "  ↓"
echo "BPF-LSM"
echo "  ↓"
echo "Ring Buffer"
echo "  ↓"
echo "KernelGuard Reader"
echo "  ↓"
echo "Zero Trust Policy"
echo

echo "=============================================================="
echo " NEXT IMPLEMENTATION TARGET"
echo "=============================================================="

echo
echo "Connect Agent PID / process ancestry directly"
echo "with the BPF event structure."
echo

