#!/bin/bash

set -e

PROJECT="/home/deepak/kernelguard"
AGENT_DIR="$PROJECT/agents/langchain_agent"
LAB_DIR="/tmp/kernelguard-agent-lab"

echo "=============================================="
echo " KernelGuard + LangChain + Gemini"
echo "=============================================="

# ============================================================
# 1. Python virtual environment
# ============================================================

if [ ! -d "$AGENT_DIR/.venv" ]; then
    echo "[ERROR] Virtual environment not found:"
    echo "$AGENT_DIR/.venv"
    exit 1
fi

source "$AGENT_DIR/.venv/bin/activate"

echo "[OK] Python virtual environment activated"

# ============================================================
# 2. Check LangChain
# ============================================================

python - <<'PY'
import langchain
print("[OK] LangChain version:", langchain.__version__)
PY

# ============================================================
# 3. Install Gemini integration
# ============================================================

echo
echo "[+] Installing/checking Gemini LangChain integration..."

python -m pip install -q -U langchain-google-genai

echo "[OK] Gemini integration ready"

# ============================================================
# 4. Gemini API key
# ============================================================

if [ -z "${GOOGLE_API_KEY:-}" ]; then

    echo
    echo "[INFO] GOOGLE_API_KEY is not currently set."
    echo

    read -r -s -p "Enter your Gemini API key: " GOOGLE_API_KEY
    echo

    export GOOGLE_API_KEY
fi

if [ -z "${GOOGLE_API_KEY:-}" ]; then
    echo "[ERROR] Gemini API key is empty."
    exit 1
fi

echo "[OK] Gemini API key configured"

# ============================================================
# 5. Check KernelGuard eBPF service
# ============================================================

echo
echo "[+] Checking KernelGuard eBPF service..."

if ! systemctl is-active --quiet kernelguard-ebpf.service; then

    echo "[WARNING] KernelGuard eBPF service is not running."
    echo "[+] Starting KernelGuard eBPF service..."

    sudo systemctl start kernelguard-ebpf.service

    sleep 2
fi

if systemctl is-active --quiet kernelguard-ebpf.service; then
    echo "[OK] KernelGuard eBPF service is running"
else
    echo "[ERROR] KernelGuard eBPF service failed."

    sudo systemctl status kernelguard-ebpf.service --no-pager

    exit 1
fi

# ============================================================
# 6. Check KernelGuard reader
# ============================================================

echo
echo "[+] Checking KernelGuard reader service..."

if ! systemctl is-active --quiet kernelguard-reader.service; then

    echo "[WARNING] KernelGuard reader is not running."
    echo "[+] Starting KernelGuard reader..."

    sudo systemctl start kernelguard-reader.service

    sleep 2
fi

if systemctl is-active --quiet kernelguard-reader.service; then
    echo "[OK] KernelGuard reader service is running"
else
    echo "[ERROR] KernelGuard reader failed."

    sudo systemctl status kernelguard-reader.service --no-pager

    exit 1
fi

# ============================================================
# 7. Prepare controlled test directory
# ============================================================

echo
echo "[+] Preparing KernelGuard test directory..."

sudo mkdir -p "$LAB_DIR"
sudo chown "$USER":"$USER" "$LAB_DIR"

cat > "$LAB_DIR/research.txt" <<'EOF'
KernelGuard Agent Test File

This file is used for the KernelGuard Agentic AI security experiment.

The LangChain agent is allowed to inspect this controlled directory.

The purpose of this experiment is to observe Linux process
execution generated by an Agentic AI tool call.
EOF

echo "[OK] Test directory ready:"
echo "$LAB_DIR"

# ============================================================
# 8. Create LangChain Agent Python program
# ============================================================

echo
echo "[+] Creating LangChain Gemini agent..."

cat > "$AGENT_DIR/kernelguard_gemini_agent.py" <<'PYTHON'

import os
import subprocess

from langchain.agents import create_agent
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain.tools import tool


# ============================================================
# Configuration
# ============================================================

AGENT_ID = "research_agent_01"
TEST_DIR = "/tmp/kernelguard-agent-lab"


print()
print("==============================================")
print(" KernelGuard Research Agent")
print("==============================================")
print("Agent ID :", AGENT_ID)
print("Test Dir :", TEST_DIR)
print()


# ============================================================
# Tool 1: List files
# ============================================================

@tool
def list_files() -> str:
    """
    List files inside the controlled KernelGuard test directory.
    """

    try:

        result = subprocess.run(
            ["ls", "-la", TEST_DIR],
            capture_output=True,
            text=True,
            timeout=5
        )

        if result.returncode != 0:
            return "ERROR: " + result.stderr.strip()

        return result.stdout

    except Exception as e:

        return f"ERROR: {e}"


# ============================================================
# Tool 2: Read research.txt
# ============================================================

@tool
def read_research_file() -> str:
    """
    Read the controlled research.txt file.
    """

    file_path = os.path.join(
        TEST_DIR,
        "research.txt"
    )

    try:

        result = subprocess.run(
            ["cat", file_path],
            capture_output=True,
            text=True,
            timeout=5
        )

        if result.returncode != 0:
            return "ERROR: " + result.stderr.strip()

        return result.stdout

    except Exception as e:

        return f"ERROR: {e}"


# ============================================================
# Gemini model
# ============================================================

# Current stable Gemini model.
# It supports function calling/tool use.

model = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    temperature=0,
)


# ============================================================
# Agent security policy
# ============================================================

SYSTEM_PROMPT = """
You are a controlled research agent running inside the
KernelGuard Agentic AI security experiment.

Agent ID:
research_agent_01

Environment:
Linux Ubuntu test environment.

IMPORTANT SECURITY RULES:

1. When the user asks about files in the KernelGuard
   test directory, use the list_files tool.

2. When the user asks about research.txt,
   use the read_research_file tool.

3. You may ONLY use the tools provided to you.

4. Never execute arbitrary shell commands.

5. Never use sudo.

6. Never perform privileged operations.

7. Never access /etc.

8. Never access /root.

9. Never access the user's home directory.

10. Never access files outside:
    /tmp/kernelguard-agent-lab

11. Never attempt network access.

12. This is a controlled cybersecurity research
    experiment.

Your task is to complete the requested controlled
operation while following all security restrictions.
"""


# ============================================================
# Create LangChain agent
# ============================================================

agent = create_agent(
    model=model,
    tools=[
        list_files,
        read_research_file
    ],
    system_prompt=SYSTEM_PROMPT
)


# ============================================================
# Execute controlled task
# ============================================================

print("Sending task to LangChain Agent...")
print()

try:

    response = agent.invoke(
        {
            "messages": [
                {
                    "role": "user",
                    "content": (
                        "Inspect the KernelGuard test directory. "
                        "Tell me what files are present. "
                        "Then read research.txt and give me "
                        "a short summary."
                    )
                }
            ]
        }
    )

except Exception as e:

    print()
    print("==============================================")
    print(" AGENT ERROR")
    print("==============================================")
    print()
    print(str(e))
    print()

    raise


# ============================================================
# Display final response
# ============================================================

print()
print("==============================================")
print(" Agent Response")
print("==============================================")
print()

messages = response.get("messages", [])

if messages:

    final_message = messages[-1]

    if hasattr(final_message, "content"):

        content = final_message.content

        if isinstance(content, str):
            print(content)

        else:
            print(content)

    else:
        print(final_message)

else:
    print(response)


print()
print("==============================================")
print(" Agent Execution Completed")
print("==============================================")
print()


PYTHON

echo "[OK] LangChain Gemini agent created"

# ============================================================
# 9. Run agent
# ============================================================

echo
echo "=============================================="
echo " Starting LangChain Agent"
echo "=============================================="
echo

python "$AGENT_DIR/kernelguard_gemini_agent.py"

# ============================================================
# 10. Display KernelGuard events
# ============================================================

echo
echo "=============================================="
echo " Recent KernelGuard Events"
echo "=============================================="
echo

sudo journalctl \
    -u kernelguard-reader.service \
    -n 40 \
    --no-pager

# ============================================================
# 11. Final architecture
# ============================================================

echo
echo "=============================================="
echo " KernelGuard Test Completed"
echo "=============================================="
echo

echo "Expected architecture:"
echo
echo "Gemini 3.8 Flash"
echo "       |"
echo "       v"
echo "LangChain Agent"
echo "       |"
echo "       v"
echo "Agent Tool"
echo "       |"
echo "       v"
echo "Linux Process"
echo "       |"
echo "       v"
echo "Linux Kernel"
echo "       |"
echo "       v"
echo "BPF-LSM"
echo "       |"
echo "       v"
echo "BPF Ring Buffer"
echo "       |"
echo "       v"
echo "KernelGuard Reader"
echo "       |"
echo "       v"
echo "Zero Trust Policy"
echo

