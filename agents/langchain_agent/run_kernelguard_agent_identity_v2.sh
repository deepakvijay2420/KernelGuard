#!/bin/bash

set -u

PROJECT="/home/deepak/kernelguard"
AGENT_DIR="$PROJECT/agents/langchain_agent"
LAB_DIR="/tmp/kernelguard-agent-lab"
IDENTITY_DIR="$PROJECT/logs/agent_identity"

mkdir -p "$IDENTITY_DIR"

TIMESTAMP=$(date +"%Y%m%d_%H%M%S")

IDENTITY_LOG="$IDENTITY_DIR/agent_identity_$TIMESTAMP.log"
EVENT_LOG="$IDENTITY_DIR/kernelguard_events_$TIMESTAMP.log"
PROCESS_LOG="$IDENTITY_DIR/process_tree_$TIMESTAMP.log"
SUMMARY_FILE="$IDENTITY_DIR/correlation_$TIMESTAMP.txt"

echo
echo "=============================================================="
echo " KernelGuard Agent Identity Correlation Test - V2"
echo "=============================================================="
echo

# ==============================================================
# 1. Activate environment
# ==============================================================

source "$AGENT_DIR/.venv/bin/activate"

echo "[OK] Python environment activated"

# ==============================================================
# 2. Gemini API key
# ==============================================================

if [ -z "${GOOGLE_API_KEY:-}" ]; then

    echo
    read -r -s -p "Gemini API key: " GOOGLE_API_KEY
    echo

    export GOOGLE_API_KEY
fi

if [ -z "${GOOGLE_API_KEY:-}" ]; then
    echo "[ERROR] Gemini API key unavailable."
    exit 1
fi

echo "[OK] Gemini API key available"

# ==============================================================
# 3. Check KernelGuard
# ==============================================================

echo
echo "=============================================================="
echo " Checking KernelGuard"
echo "=============================================================="

sudo systemctl start kernelguard-ebpf.service
sleep 1

sudo systemctl start kernelguard-reader.service
sleep 2

if systemctl is-active --quiet kernelguard-ebpf.service; then
    echo "[OK] KernelGuard eBPF service running"
else
    echo "[ERROR] KernelGuard eBPF service failed"
    exit 1
fi

if systemctl is-active --quiet kernelguard-reader.service; then
    echo "[OK] KernelGuard reader running"
else
    echo "[ERROR] KernelGuard reader failed"
    exit 1
fi

# ==============================================================
# 4. Prepare test directory
# ==============================================================

echo
echo "=============================================================="
echo " Preparing Test Environment"
echo "=============================================================="

sudo mkdir -p "$LAB_DIR"
sudo chown "$USER":"$USER" "$LAB_DIR"

cat > "$LAB_DIR/research.txt" <<'EOF'
KernelGuard Agent Identity Experiment

Agent ID:
research_agent_01

Purpose:
Test whether Linux process executions generated by
an Agentic AI can be correlated with the Agent process.
EOF

echo "[OK] Test directory ready"

# ==============================================================
# 5. Create agent
# ==============================================================

cat > "$AGENT_DIR/kernelguard_identity_agent_v2.py" <<'PYTHON'

import os
import subprocess
import time

from langchain.agents import create_agent
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain.tools import tool


AGENT_ID = "research_agent_01"
TEST_DIR = "/tmp/kernelguard-agent-lab"
PID_FILE = "/tmp/kernelguard_agent_pid"


# --------------------------------------------------------------
# Record agent PID
# --------------------------------------------------------------

AGENT_PID = os.getpid()
PARENT_PID = os.getppid()

with open(PID_FILE, "w") as f:
    f.write(str(AGENT_PID))


print()
print("==================================================")
print(" KernelGuard Research Agent")
print("==================================================")
print("Agent ID :", AGENT_ID)
print("Agent PID:", AGENT_PID)
print("Parent PID:", PARENT_PID)
print("Test Dir :", TEST_DIR)
print()


# --------------------------------------------------------------
# Tool 1
# --------------------------------------------------------------

@tool
def list_files() -> str:
    """
    List files in the controlled KernelGuard directory.
    """

    print()
    print("[TOOL] list_files()")
    print("[TOOL PID]", os.getpid())

    result = subprocess.run(
        ["/usr/bin/ls", "-la", TEST_DIR],
        capture_output=True,
        text=True,
        timeout=5
    )

    return result.stdout


# --------------------------------------------------------------
# Tool 2
# --------------------------------------------------------------

@tool
def read_research_file() -> str:
    """
    Read the controlled research.txt file.
    """

    print()
    print("[TOOL] read_research_file()")
    print("[TOOL PID]", os.getpid())

    result = subprocess.run(
        ["/usr/bin/cat", f"{TEST_DIR}/research.txt"],
        capture_output=True,
        text=True,
        timeout=5
    )

    return result.stdout


# --------------------------------------------------------------
# Gemini
# --------------------------------------------------------------

model = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash"
)


# --------------------------------------------------------------
# Security policy
# --------------------------------------------------------------

SYSTEM_PROMPT = """
You are research_agent_01.

You are running inside the KernelGuard Linux
security experiment.

You have only two allowed operations:

1. List files in:
   /tmp/kernelguard-agent-lab

2. Read:
   /tmp/kernelguard-agent-lab/research.txt

Use the provided tools.

Never use sudo.

Never execute arbitrary shell commands.

Never access /etc.

Never access /root.

Never access the user's home directory.

Never access files outside the controlled directory.

Never perform network operations.

Never perform privileged operations.
"""


# --------------------------------------------------------------
# Create agent
# --------------------------------------------------------------

agent = create_agent(
    model=model,
    tools=[
        list_files,
        read_research_file
    ],
    system_prompt=SYSTEM_PROMPT
)


# --------------------------------------------------------------
# Run task
# --------------------------------------------------------------

print("Sending task to LangChain Agent...")
print()

response = agent.invoke(
    {
        "messages": [
            {
                "role": "user",
                "content": (
                    "List the files in the KernelGuard test "
                    "directory and then read research.txt. "
                    "Give me a short summary."
                )
            }
        ]
    }
)


# --------------------------------------------------------------
# Display response
# --------------------------------------------------------------

print()
print("==================================================")
print(" Agent Response")
print("==================================================")
print()

messages = response.get("messages", [])

if messages:

    final_message = messages[-1]

    if hasattr(final_message, "content"):
        print(final_message.content)
    else:
        print(final_message)

print()
print("Agent execution completed.")

time.sleep(2)

PYTHON

echo "[OK] Agent program created"

# ==============================================================
# 6. Record exact experiment start time
# ==============================================================

START_TIME=$(date --iso-8601=seconds)

echo
echo "[INFO] Experiment start time:"
echo "$START_TIME"

# ==============================================================
# 7. Remove previous PID
# ==============================================================

rm -f /tmp/kernelguard_agent_pid

# ==============================================================
# 8. Start agent
# ==============================================================

echo
echo "=============================================================="
echo " Starting Agent"
echo "=============================================================="
echo

python "$AGENT_DIR/kernelguard_identity_agent_v2.py" \
    > "$IDENTITY_LOG" 2>&1 &

AGENT_LAUNCHER_PID=$!

echo "[OK] Agent launcher PID: $AGENT_LAUNCHER_PID"

# ==============================================================
# 9. Wait for Agent PID
# ==============================================================

AGENT_PID=""

for i in $(seq 1 30); do

    if [ -f /tmp/kernelguard_agent_pid ]; then

        AGENT_PID=$(cat /tmp/kernelguard_agent_pid)

        if [ -n "$AGENT_PID" ]; then
            break
        fi

    fi

    sleep 0.5

done

if [ -z "$AGENT_PID" ]; then

    echo "[ERROR] Agent PID not found"

    cat "$IDENTITY_LOG"

    kill "$AGENT_LAUNCHER_PID" 2>/dev/null || true

    exit 1
fi

echo
echo "[OK] Agent PID: $AGENT_PID"

# ==============================================================
# 10. Capture process information
# ==============================================================

echo
echo "=============================================================="
echo " Agent Process Identity"
echo "=============================================================="

{
    echo "Agent ID: research_agent_01"
    echo "Agent PID: $AGENT_PID"
    echo
    echo "Process:"
    ps -p "$AGENT_PID" -o pid,ppid,uid,user,comm,args

    PARENT_PROCESS_PID=$(ps -p "$AGENT_PID" -o ppid= | tr -d ' ')

    echo
    echo "Parent PID: $PARENT_PROCESS_PID"

    if [ -n "$PARENT_PROCESS_PID" ]; then
        echo
        echo "Parent process:"
        ps -p "$PARENT_PROCESS_PID" \
            -o pid,ppid,uid,user,comm,args
    fi

    echo
    echo "Process tree:"
    pstree -aps "$AGENT_PID" 2>/dev/null || true

} | tee "$PROCESS_LOG"

# ==============================================================
# 11. Wait for agent
# ==============================================================

echo
echo "=============================================================="
echo " Waiting for Agent Completion"
echo "=============================================================="

wait "$AGENT_LAUNCHER_PID" || true

# Give KernelGuard reader time to flush events
sleep 2

# ==============================================================
# 12. Collect KernelGuard journal
# ==============================================================

echo
echo "=============================================================="
echo " KernelGuard Events"
echo "=============================================================="

sudo journalctl \
    -u kernelguard-reader.service \
    --since "$START_TIME" \
    --no-pager \
    | tee "$EVENT_LOG"

# ==============================================================
# 13. Search for executions
# ==============================================================

echo
echo "=============================================================="
echo " Searching for Agent Tool Executions"
echo "=============================================================="

echo

grep -E \
    "ls|cat|EXEC|research|kernelguard-agent-lab" \
    "$EVENT_LOG" \
    || echo "[WARNING] No matching events found in journal."

# ==============================================================
# 14. Display Agent output
# ==============================================================

echo
echo "=============================================================="
echo " Agent Execution Log"
echo "=============================================================="

cat "$IDENTITY_LOG"

# ==============================================================
# 15. Create summary
# ==============================================================

cat > "$SUMMARY_FILE" <<EOF
KernelGuard Agent Identity Correlation Experiment
==================================================

Agent ID:
research_agent_01

Agent PID:
$AGENT_PID

Experiment start:
$START_TIME

Test directory:
$LAB_DIR

Expected tool processes:

/usr/bin/ls
/usr/bin/cat

Agent process information:
$PROCESS_LOG

KernelGuard events:
$EVENT_LOG

Agent execution:
$IDENTITY_LOG

Current identity model:

Agent ID
    |
    v
Agent PID
    |
    v
Agent Tool
    |
    v
Linux Process
    |
    v
BPF-LSM
    |
    v
KernelGuard Reader
EOF

# ==============================================================
# 16. Final result
# ==============================================================

echo
echo "=============================================================="
echo " EXPERIMENT COMPLETED"
echo "=============================================================="

echo
echo "Agent ID : research_agent_01"
echo "Agent PID: $AGENT_PID"

echo
echo "Logs:"
echo "$IDENTITY_DIR"

echo
echo "Summary:"
echo "$SUMMARY_FILE"

echo
echo "=============================================================="
echo " NEXT STEP"
echo "=============================================================="

echo
echo "If /usr/bin/ls and /usr/bin/cat appear in the"
echo "KernelGuard events, the Agent -> Linux -> BPF-LSM"
echo "correlation is confirmed."
echo

echo "Then we will add the Agent ID/cgroup information"
echo "directly into the KernelGuard event structure."
echo

